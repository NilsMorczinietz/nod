"""Generates the per-agent notification icons from the simple-icons package.

Notifications show the icon of the agent that asks (Claude, Cursor, Gemini, ...);
Android tints small icons, so only the silhouette matters. Unknown agents keep
the Nod mark (ic_stat_nod.xml, see generate_icons.py).

Run from the repo root with an unpacked simple-icons npm package:

    npm pack simple-icons@16.38.1 && tar -xzf simple-icons-16.38.1.tgz
    python3 android/scripts/generate_agent_icons.py package

Writes app/src/main/res/drawable/ic_stat_agent_<name>.xml. Add new agents to
AGENTS here and to notifications/AgentBrand.kt.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"

# drawable suffix -> simple-icons slug
AGENTS = {
    "claude": "claude",
    "cursor": "cursor",
    "gemini": "googlegemini",
    "windsurf": "windsurf",
    "copilot": "githubcopilot",
    "cline": "cline",
    "zed": "zedindustries",
    "opencode": "opencode",
    "warp": "warp",
    "mistral": "mistralai",
}

# simple-icons fill the whole 24x24 box; status-bar icons want a ~1dp margin.
SCALE = 22 / 24
OFFSET = 1.0


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    icons = Path(sys.argv[1]) / "icons"
    for name, slug in AGENTS.items():
        svg = (icons / f"{slug}.svg").read_text()
        title = re.search(r"<title>(.*?)</title>", svg).group(1)
        paths = re.findall(r'<path d="([^"]+)"', svg)
        if len(paths) != 1:
            sys.exit(f"{slug}: expected one path, found {len(paths)}")
        (OUT / f"ic_stat_agent_{name}.xml").write_text(
            f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Notification icon for {title}. Generated by android/scripts/generate_agent_icons.py
     from simple-icons ({slug}.svg, CC0); the mark is a trademark of its owner. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <group
        android:scaleX="{SCALE:.4f}"
        android:scaleY="{SCALE:.4f}"
        android:translateX="{OFFSET}"
        android:translateY="{OFFSET}">
        <path
            android:fillColor="#FFFFFFFF"
            android:pathData="{paths[0]}" />
    </group>
</vector>
"""
        )
        print(f"ic_stat_agent_{name}.xml  {title}")


if __name__ == "__main__":
    main()
