"""Generates the Android icon vector drawables from design/mark.svg.

Run from the repo root:  python3 android/scripts/generate_icons.py
Writes app/src/main/res/drawable/{ic_launcher_foreground,ic_launcher_monochrome,ic_stat_nod}.xml
and prints the bitmap cells for ui/components/NodMark.kt.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MARK = ROOT / "design" / "mark.svg"
OUT = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"
GRID = 11
VIEW = 24.0  # mark.svg viewBox


def cells() -> list[tuple[int, int]]:
    """(col, row) of every pixel in the mark, recovered from the rect positions."""
    cell = VIEW / GRID
    found = []
    for x, y in re.findall(r'<rect x="([\d.]+)" y="([\d.]+)"', MARK.read_text()):
        found.append((round(float(x) / cell - 0.05), round(float(y) / cell - 0.05)))
    return sorted(set(found))


def rounded_rect(x: float, y: float, s: float, r: float) -> str:
    if r <= 0:
        return f"M{x:.3f},{y:.3f}h{s:.3f}v{s:.3f}h{-s:.3f}z"
    return (
        f"M{x + r:.3f},{y:.3f}h{s - 2 * r:.3f}a{r:.3f},{r:.3f} 0 0 1 {r:.3f},{r:.3f}"
        f"v{s - 2 * r:.3f}a{r:.3f},{r:.3f} 0 0 1 {-r:.3f},{r:.3f}"
        f"h{-(s - 2 * r):.3f}a{r:.3f},{r:.3f} 0 0 1 {-r:.3f},{-r:.3f}"
        f"v{-(s - 2 * r):.3f}a{r:.3f},{r:.3f} 0 0 1 {r:.3f},{-r:.3f}z"
    )


def path_data(size: float, origin: float, gap: float, radius: float) -> str:
    cell = size / GRID
    inner = cell * (1 - gap)
    return "".join(
        rounded_rect(origin + c * cell + (cell - inner) / 2, origin + r * cell + (cell - inner) / 2, inner, inner * radius)
        for c, r in cells()
    )


def vector(width: int, viewport: float, fill: str, data: str, comment: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by android/scripts/generate_icons.py from design/mark.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width}dp"
    android:height="{width}dp"
    android:viewportWidth="{viewport:g}"
    android:viewportHeight="{viewport:g}">
    <path
        android:fillColor="{fill}"
        android:pathData="{data}" />
</vector>
"""


def main() -> None:
    # Adaptive icon: the mark at ~37 % of the 108 dp canvas, centred. Launchers crop to a circle
    # (~72 dp visible), so this reads as roughly half of the visible icon.
    launcher = path_data(size=40, origin=34, gap=0.14, radius=0.22)
    (OUT / "ic_launcher_foreground.xml").write_text(
        vector(108, 108, "@color/nod_icon_foreground", launcher, "Launcher foreground: teal pixel mark."))
    (OUT / "ic_launcher_monochrome.xml").write_text(
        vector(108, 108, "#FFFFFFFF", launcher, "Themed-icon layer: the mark."))
    # Status bar icon: closed gaps and square cells so it stays crisp at 24 dp.
    (OUT / "ic_stat_nod.xml").write_text(
        vector(24, 24, "#FFFFFFFF", path_data(size=24, origin=0, gap=0.0, radius=0.0), "Notification icon: mark without gaps."))
    print("cells:", cells())


if __name__ == "__main__":
    main()
