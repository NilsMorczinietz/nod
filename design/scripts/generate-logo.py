"""Generates the Nod mark as a pixel grid (matches the Geist Pixel Square type).

The mark is a "head" (disc) above an arc – the moment of a nod – rasterised onto
a square grid of rounded pixels. Run:  python3 design/scripts/generate-logo.py
Outputs (next to this script's parent): logo.svg, logo-desktop.svg, mark.svg, mark-mono.svg.
"""
from __future__ import annotations

from pathlib import Path

TEAL = "#007273"
WHITE = "#FFFFFF"
GRID = 11  # cells per side of the mark


# Hand-tuned bitmap: a round "head" above a smile-shaped arc.
BITMAP = """
...........
....###....
...#####...
...#####...
...#####...
....###....
...........
.#.......#.
.##.....##.
..#######..
...........
"""


def cells() -> list[tuple[int, int]]:
    """Returns (col, row) cells that belong to the mark."""
    rows = [line for line in BITMAP.strip().splitlines()]
    assert len(rows) == GRID and all(len(r) == GRID for r in rows)
    return [(c, r) for r, line in enumerate(rows) for c, ch in enumerate(line) if ch == "#"]


def pixels(size: float, origin: float, fill: str, gap: float = 0.14, radius: float = 0.22) -> str:
    cell = size / GRID
    inner = cell * (1 - gap)
    rx = inner * radius
    out = []
    for col, row in cells():
        x = origin + col * cell + (cell - inner) / 2
        y = origin + row * cell + (cell - inner) / 2
        out.append(
            f'<rect x="{x:.2f}" y="{y:.2f}" width="{inner:.2f}" height="{inner:.2f}" rx="{rx:.2f}" fill="{fill}"/>'
        )
    return "\n    ".join(out)


def svg(view: int, body: str, comment: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {view} {view}">\n'
        f"  <!-- {comment} Generated by design/scripts/generate-logo.py. -->\n"
        f"  {body}\n</svg>\n"
    )


def main() -> None:
    out = Path(__file__).resolve().parent.parent
    # App icon: white tile, teal pixel mark at ~50 % of the tile (smaller, airy).
    mark = 256
    logo = (
        f'<rect width="512" height="512" rx="116" fill="{WHITE}"/>\n'
        f'  <g>\n    {pixels(mark, (512 - mark) / 2, TEAL)}\n  </g>'
    )
    (out / "logo.svg").write_text(svg(512, logo, "Nod app icon: teal pixel mark on white."))
    # Desktop app icon (exe, tray, taskbar): white mark on transparent, no tile.
    # Without a tile the mark fills ~90 % of the canvas so it reads at 16 px.
    span = 512 * 0.9 * GRID / 9  # the bitmap leaves one empty cell on each side
    (out / "logo-desktop.svg").write_text(
        svg(
            512,
            f"<g>\n    {pixels(span, (512 - span) / 2, WHITE)}\n  </g>",
            "Nod desktop icon: white pixel mark on transparent.",
        )
    )
    # Mark only (teal), for in-app use on light surfaces.
    (out / "mark.svg").write_text(svg(24, f"<g>\n    {pixels(24, 0, TEAL)}\n  </g>", "Nod mark, teal."))
    # Monochrome mark (currentColor) for notification small icons, tray, island.
    (out / "mark-mono.svg").write_text(
        svg(24, f"<g>\n    {pixels(24, 0, 'currentColor', gap=0.1)}\n  </g>", "Nod mark, monochrome.")
    )
    print(f"{len(cells())} pixels on a {GRID}x{GRID} grid")
    for row in range(GRID):
        print("".join("██" if (c, row) in cells() else "· " for c in range(GRID)))


if __name__ == "__main__":
    main()
