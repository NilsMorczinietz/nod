// Generates src/styles/tokens.css from the shared design/tokens.json (v4).
// Motion curves are imported directly from tokens.json by src/lib/motion.ts.
import { readFile, writeFile } from 'node:fs/promises'

const tokens = JSON.parse(
  await readFile(new URL('../../design/tokens.json', import.meta.url), 'utf8'),
)

const kebab = (key) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)
const entries = (object) => Object.entries(object).filter(([key]) => !key.startsWith('$'))
const lines = (list, indent = '  ') => list.map((line) => `${indent}${line}`).join('\n')
const lower = (value) => (value.startsWith('#') ? value.toLowerCase() : value)

// Teal is for fills, dots and rings; text that would be teal uses
// --c-primary-text, which is the foreground colour in dark mode.
const palette = (scheme) => [
  ...entries(tokens.color[scheme]).map(([key, value]) => `--c-${kebab(key)}: ${lower(value)};`),
  `--c-primary-text: var(--c-${scheme === 'dark' ? 'foreground' : 'primary'});`,
]
const shadows = (scheme) =>
  entries(tokens.shadow[scheme]).map(([key, value]) => `--shadow-${kebab(key)}: ${value};`)
const island = entries(tokens.color.island).map(
  ([key, value]) => `--island-${kebab(key)}: ${lower(value)};`,
)
const scale = (prefix, object, unit = '') =>
  entries(object).map(([key, value]) => `--${prefix}-${kebab(key)}: ${value}${unit};`)

const FAMILIES = {
  sans: `'Geist Variable', 'Geist', 'Segoe UI Variable Text', system-ui, sans-serif`,
  mono: `'Geist Mono Variable', 'Geist Mono', 'Cascadia Code', ui-monospace, monospace`,
  pixel: `'Geist Pixel Square', 'Geist Mono Variable', ui-monospace, monospace`,
}

const typeScale = entries(tokens.type)
  .filter(([key]) => key !== 'family')
  .flatMap(([name, t]) => [
    `--type-${name}-size: ${t.size}px;`,
    ...(t.sizeLarge ? [`--type-${name}-size-large: ${t.sizeLarge}px;`] : []),
    `--type-${name}-weight: ${t.weight};`,
    ...(t.tracking !== undefined ? [`--type-${name}-tracking: ${t.tracking}em;`] : []),
    ...(t.lineHeight !== undefined ? [`--type-${name}-line: ${t.lineHeight};`] : []),
  ])

const motion = entries(tokens.motion)
  .filter(([, value]) => typeof value === 'object')
  .flatMap(([name, m]) => [
    `--motion-${name}-duration: ${m.duration}ms;`,
    `--motion-${name}-easing: ${m.easing};`,
  ])

const { badge } = tokens
const css = `/* Generated by scripts/gen-tokens.mjs from design/tokens.json (v${tokens.version}) – do not edit. */
:root {
  color-scheme: dark light;
${lines(palette('dark'))}
${lines(shadows('dark'))}
${lines(island)}
  --shadow-island: ${tokens.shadow.island};
  --outline-waiting: ${tokens.shadow.waitingOutline};
${lines(scale('radius', tokens.radius, 'px'))}
${lines(scale('space', tokens.spacing, 'px'))}
  --badge-radius: ${badge.radius}px;
  --badge-padding: ${badge.paddingY}px ${badge.paddingX}px;
  --font-sans: ${FAMILIES.sans};
  --font-mono: ${FAMILIES.mono};
  --font-pixel: ${FAMILIES.pixel};
${lines(typeScale)}
${lines(motion)}
}

@media (prefers-color-scheme: light) {
  :root {
${lines([...palette('light'), ...shadows('light')], '    ')}
  }
}

/* Explicit themes (app theme setting, island theme) override the system. */
.theme-dark {
  color-scheme: dark;
${lines([...palette('dark'), ...shadows('dark')])}
}

.theme-light {
  color-scheme: light;
${lines([...palette('light'), ...shadows('light')])}
}
`
await writeFile(new URL('../src/styles/tokens.css', import.meta.url), css)
