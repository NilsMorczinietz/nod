<!--
  The Nod pixel mark, read from design/mark-mono.svg (generated by
  design/scripts/generate-logo.py) so there is one source of truth.
  Colour: `--mark-color` if set (island: white on dark, teal on light),
  otherwise the brand teal.
-->
<script lang="ts" module>
  import source from '../../../design/mark-mono.svg?raw'

  /** The squares of the mark, parsed once. */
  const PIXELS = [...source.matchAll(/<rect ([^>]*)\/>/g)].map(([, attrs]) => {
    const get = (name: string) => Number(new RegExp(`${name}="([\\d.]+)"`).exec(attrs!)?.[1] ?? 0)
    return { x: get('x'), y: get('y'), size: get('width'), r: get('rx') }
  })
</script>

<script lang="ts">
  let { size = 24 }: { size?: number } = $props()
</script>

<svg viewBox="0 0 24 24" width={size} height={size} aria-hidden="true">
  {#each PIXELS as p, i (i)}<rect x={p.x} y={p.y} width={p.size} height={p.size} rx={p.r} />{/each}
</svg>

<style>
  svg {
    flex: none;
    display: block;
    fill: var(--mark-color, var(--c-button-primary));
  }
</style>
